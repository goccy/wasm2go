package gcasm

import (
	"strings"
	"testing"
)

// The capture's diagnostics keep what says why the build failed out of the
// listing it is buried in: a compile error, and also a tool that did not
// finish — killed (out of memory) or crashed — whose words have no file
// position.
func TestCaptureDiagnosticsKeepWhyTheBuildFailed(t *testing.T) {
	listing := strings.Repeat("\t0x0000 00000 (x.go:1)\tTEXT\tmain.f(SB), ABIInternal, $0-0\n", 50)
	for _, c := range []struct{ name, failure string }{
		{"a compile error", "base/fn.go:12:3: undefined: Fn9\n"},
		{"a killed compiler", "/usr/local/go/pkg/tool/linux_arm64/compile: signal: killed\n"},
		{"a compiler out of memory", "fatal error: runtime: out of memory\n"},
		{"a compiler that panicked", "panic: runtime error: index out of range [3] with length 3\n"},
		{"an internal compiler error", "<autogenerated>:1: internal compiler error: bad\n"},
	} {
		t.Run(c.name, func(t *testing.T) {
			out := diagnostics([]byte("# github.com/goccy/perlwasm2go/base\n" + listing + c.failure + listing))
			if !strings.Contains(out, strings.TrimSuffix(c.failure, "\n")) {
				t.Errorf("diagnostics lost %q:\n%s", c.failure, out)
			}
			if strings.Contains(out, "TEXT") {
				t.Errorf("diagnostics kept the listing:\n%s", out)
			}
		})
	}
}
