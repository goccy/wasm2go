// hostSyscallNumber returns the number x86-64 has the guest's system call of
// the number under (HostSyscalls): the call of the same name, which x86-64
// has for every one the Linux ABI assigns. The numbers from
// linuxSysPidfdSendSignal on are every architecture's.
func hostSyscallNumber(number int64) (uintptr, bool) {
	if number >= linuxSysPidfdSendSignal {
		return uintptr(number), true
	}
	n, ok := hostSyscallNumbers[number]
	return n, ok
}

